// Regenerates src/lib/themeEditor/registry.js from the storefront's SECTION_REGISTRY (a separate repo, so the ERP keeps a
// generated copy rather than importing it). Run after the storefront gains/changes a section type:
//   node scripts/sync-section-registry.mjs [path-to-storefront-layout.ts]
import { execFileSync } from "node:child_process";
import { mkdtempSync, writeFileSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(process.argv[2] || join(here, "..", "..", "neezam-erp-worker", "storefront", "src", "lib", "storefront-layout.ts"));
const esbuild = resolve(dirname(src), "..", "..", "node_modules", ".bin", process.platform === "win32" ? "esbuild.cmd" : "esbuild");
const tmp = mkdtempSync(join(tmpdir(), "ne-registry-"));
const out = join(tmp, "layout.mjs");
execFileSync(esbuild, [src, "--bundle", "--format=esm", `--outfile=${out}`, "--log-level=error"], { shell: process.platform === "win32" });
const mod = await import(pathToFileURL(out).href);

const registry = mod.SECTION_REGISTRY.map((m) => ({
  type: m.type, label: m.label, group: m.group, locked: !!m.locked, templates: m.templates, defaults: m.defaults, schema: m.schema,
}));
const body = `// GENERATED by scripts/sync-section-registry.mjs from neezam-erp-worker/storefront/src/lib/storefront-layout.ts
// Do not edit by hand. These are the section types the storefront renderer really supports.
export const SECTION_REGISTRY = ${JSON.stringify(registry, null, 1)};
`;
writeFileSync(join(here, "..", "src", "lib", "themeEditor", "registry.js"), body);
console.log(`registry.js written: ${registry.length} section types (source ${src})`);
void readFileSync;
