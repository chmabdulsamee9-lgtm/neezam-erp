// Generates src/lib/themeV2/engine.generated.js from the single source of the v2 theme schema and engine core
// (neezam-erp-worker/shared/theme-v2). The ERP keeps a bundled copy because it is a separate repo; never edit it by hand.
//   node scripts/sync-theme-v2.mjs            regenerate
//   node scripts/sync-theme-v2.mjs --check    exit 1 when the copy is out of date (drift), 0 when it matches;
//                                             skipped (exit 0) when the worker repo is not next to this one
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync, existsSync, readdirSync, statSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname, resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const here = dirname(fileURLToPath(import.meta.url));
const check = process.argv.includes("--check");
const srcDir = resolve(process.argv.find((a) => !a.startsWith("--") && a !== process.argv[0] && a !== process.argv[1]) || join(here, "..", "..", "neezam-erp-worker", "shared", "theme-v2"));
const outFile = join(here, "..", "src", "lib", "themeV2", "engine.generated.js");

if (!existsSync(join(srcDir, "index.js"))) {
  if (check) { console.log(`theme-v2 drift check skipped: source not found at ${srcDir}`); process.exit(0); }
  console.error(`source not found: ${srcDir}`);
  process.exit(1);
}

function files(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? files(p) : f.endsWith(".js") ? [p] : [];
  }).sort();
}
const sourceHash = createHash("sha256");
for (const f of files(srcDir)) sourceHash.update(relative(srcDir, f).replace(/\\/g, "/")).update(readFileSync(f, "utf8").replace(/\r\n/g, "\n"));
const digest = sourceHash.digest("hex").slice(0, 16);

const header = (d) => `// GENERATED by scripts/sync-theme-v2.mjs from neezam-erp-worker/shared/theme-v2 (source hash ${d}).\n// Do not edit by hand: change the shared source and re-run the script. npm test fails when this copy drifts.\n`;

if (check) {
  const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : "";
  const m = /source hash ([0-9a-f]{16})/.exec(current);
  if (!m || m[1] !== digest) {
    console.error(`theme-v2 copy is out of date (copy ${m ? m[1] : "missing"}, source ${digest}). Run: node scripts/sync-theme-v2.mjs`);
    process.exit(1);
  }
  console.log(`theme-v2 copy matches the source (${digest})`);
  process.exit(0);
}

const esbuild = resolve(srcDir, "..", "..", "storefront", "node_modules", ".bin", process.platform === "win32" ? "esbuild.cmd" : "esbuild");
const tmp = mkdtempSync(join(tmpdir(), "ne-theme-v2-"));
const out = join(tmp, "engine.js");
execFileSync(esbuild, [join(srcDir, "index.js"), "--bundle", "--format=esm", `--outfile=${out}`, "--log-level=error", "--legal-comments=none"], { shell: process.platform === "win32" });
writeFileSync(outFile, header(digest) + readFileSync(out, "utf8"));
console.log(`engine.generated.js written (source hash ${digest})`);
